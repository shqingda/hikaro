import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { writeFile } from 'node:fs/promises';
const output = fileURLToPath(new URL('.', import.meta.url));
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', msg => { if (['error','warning'].includes(msg.type())) errors.push(msg.text()); });
const base = process.env.HIKARO_DRAFT_URL ?? 'http://127.0.0.1:4173/docs/design/client-reboot/';
const screenshots = [];
async function shot(selector, name) { await page.waitForFunction(() => document.querySelector('#toast').hidden); await page.locator(selector).screenshot({ path: output + name }); screenshots.push(name); }
const checks = [];
await page.goto(base);
await page.evaluate(() => document.fonts.ready);
await shot('#desktop', 'desktop.png');
assert.equal(await page.locator('#desktop [data-approve]').evaluate(el => { const r = el.getBoundingClientRect(); const parent = el.closest('.conversation-scroll').getBoundingClientRect(); return r.bottom <= parent.bottom; }), true, 'desktop approval controls visible before scrolling');
await page.screenshot({ path: output + 'overview.png', fullPage: true });
screenshots.push('overview.png');
await page.locator('#desktop-input').fill('保持中文草稿 🌤️');
await page.getByRole('button', { name:'模拟断线', exact:true }).click();
assert.equal(await page.locator('#desktop [data-approve]').isDisabled(), true);
assert.equal(await page.locator('.send').isDisabled(), true);
assert.equal(await page.locator('#desktop-input').inputValue(), '保持中文草稿 🌤️');
checks.push('offline disables authorization and send; Chinese/emoji draft retained');
await page.getByRole('button', { name:'模拟重连', exact:true }).click();
await page.locator('#desktop [data-approve]').click();
assert.match(await page.locator('#desktop .approval-result').textContent(), /示例检查已完成/);
await page.getByRole('button', { name:'手机', exact:true }).click();
assert.equal(await page.locator('#mobile .approval').isVisible(), false);
checks.push('approval state is reflected on both simulated clients');
await page.getByRole('button', { name:'重置', exact:true }).click();
await shot('#mobile', 'mobile.png');
assert.equal(await page.locator('#mobile [data-approve]').evaluate(el => { const r = el.getBoundingClientRect(); const parent = el.closest('.phone-content').getBoundingClientRect(); return r.bottom <= parent.bottom; }), true, 'phone approval controls visible before scrolling');
await page.locator('#mobile nav [data-phone="conversation"]').click();
await page.locator('#phone-input').fill('请保留原有变更');
await page.locator('.phone-composer button').click();
assert.match(await page.locator('.phone-sent').textContent(), /请保留原有变更/);
await page.locator('#mobile nav [data-phone="approvals"]').click();
await page.locator('#mobile [data-deny]').click();
assert.match(await page.locator('#mobile .approval-result').textContent(), /已拒绝/);
checks.push('mobile navigation, draft submission and denial update visible state');
await page.getByRole('button', { name:'桌面', exact:true }).click();
await page.keyboard.press('Control+k');
assert.equal(await page.locator('#command-dialog').isVisible(), true);
await page.keyboard.press('Escape');
assert.equal(await page.locator('#command-dialog').isVisible(), false);
await page.locator('.workspace-nav [data-panel="changes"]').click();
assert.equal(await page.locator('#panel-changes').isVisible(), true);
await page.locator('.workspace-nav [data-panel="devices"]').click();
await page.locator('#pair').click();
assert.equal(await page.locator('#pair-dialog').isVisible(), true);
await page.keyboard.press('Escape');
checks.push('keyboard command dialog, Escape, change view and pairing flow work');
await page.getByRole('button', { name:'连接方式', exact:true }).click();
await shot('#architecture', 'architecture.png');
await page.getByRole('button', { name:'桌面', exact:true }).click();
await page.getByRole('button', { name:'重置', exact:true }).click();
await page.locator('.workspace-nav [data-panel="conversation"]').click();
await page.locator('#theme').click();
await shot('#desktop', 'desktop-dark.png');
await page.locator('#theme').click();
const widths = [390, 600, 768, 1024, 1440];
for (const width of widths) {
  await page.setViewportSize({ width, height: 900 });
  for (const view of ['desktop','mobile','architecture']) {
    await page.locator(`[data-view="${view}"]`).click();
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    assert.equal(overflow, false, `page overflow at ${width}/${view}`);
  }
}
checks.push('no document horizontal overflow at 390, 600, 768, 1024, 1440 px in all three views');
await page.setViewportSize({ width:390, height:900 });
await page.emulateMedia({ reducedMotion:'reduce' });
await page.locator('[data-view="mobile"]').click();
await shot('#mobile', 'mobile-narrow.png');
assert.equal(await page.locator('#connection').evaluate(el => getComputedStyle(el).transitionDuration), '0s');
assert.equal(await page.locator('#mobile [data-approve]').evaluate(el => { const r = el.getBoundingClientRect(); const parent = el.closest('.phone-content').getBoundingClientRect(); return r.bottom <= parent.bottom; }), true, 'narrow phone approval controls visible before scrolling');
checks.push('reduced motion removes transition; narrow phone layout and initially visible authorization controls verified');
assert.equal(errors.length, 0, errors.join('\n'));
const names = await page.locator('button').evaluateAll(buttons => buttons.filter(el => !el.textContent.trim() && !el.getAttribute('aria-label')).length);
assert.equal(names, 0);
checks.push('no browser errors/warnings; every button has text or an accessible name');
const record = { date:'2026-10-18', browser:await browser.version(), platform:process.platform, node:process.version, checks, errors, screenshots, limitations:['No production host, native shell or model connected','Browser checks do not validate native IME, VoiceOver, TalkBack, performance budgets or crypto','Mock drafts survive view/offline transitions only; page reload discards them'] };
await writeFile(output + 'review.json', JSON.stringify(record, null, 2) + '\n');
console.log(JSON.stringify(record, null, 2));
await browser.close();
